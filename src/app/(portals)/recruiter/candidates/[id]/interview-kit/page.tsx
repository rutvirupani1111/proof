import { ArrowLeft, MessagesSquare, UserX } from "lucide-react";
import type { Metadata } from "next";
import Link from "next/link";
import { InterviewKitView } from "@/components/recruiter/interview-kit";
import { InterviewKitToolbar } from "@/components/recruiter/interview-kit-toolbar";
import { Button } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/empty-state";
import { PageHeader } from "@/components/ui/page-header";
import { requireRole } from "@/server/auth/guard";
import { buildInterviewKit, kitInputFrom, kitText } from "@/server/recruiter/interview-kit";
import { getCandidate } from "@/server/recruiter/queries";
import { recruiterScopeOf } from "@/server/recruiter/scope";

export const metadata: Metadata = { title: "Interview kit" };
export const dynamic = "force-dynamic";

export default async function InterviewKitPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const user = await requireRole("recruiter", `/recruiter/candidates/${id}/interview-kit`);
  const c = await getCandidate(recruiterScopeOf(user), id);

  if (!c) {
    return (
      <EmptyState
        icon={UserX}
        title="This profile is not available"
        description="The student may have hidden their profile from recruiters."
        action={
          <Button variant="secondary" asChild>
            <Link href="/recruiter/search">Back to search</Link>
          </Button>
        }
      />
    );
  }

  const kit = buildInterviewKit(kitInputFrom(c));

  return (
    <>
      <Link
        href={`/recruiter/candidates/${c.user.id}`}
        className="mb-4 inline-flex items-center gap-1.5 text-sm text-muted hover:text-ink print:hidden"
      >
        <ArrowLeft className="size-4" aria-hidden /> Back to dossier
      </Link>
      <PageHeader
        eyebrow="Interview kit"
        title={c.user.name}
        description="Every question is built from this candidate's verified work: their repositories, live deployments, skill checks and mentor endorsements. Ask about real decisions, not trivia."
        actions={kit.hasEvidence ? <InterviewKitToolbar text={kitText(kit, c.user.name)} /> : undefined}
      />
      {kit.hasEvidence ? (
        <InterviewKitView kit={kit} candidateId={c.user.id} />
      ) : (
        <EmptyState
          icon={MessagesSquare}
          title="Nothing to ask about yet"
          description="Questions appear once the candidate has verified repositories, deployments, passed checks or endorsements."
        />
      )}
      <p className="mt-6 hidden font-mono text-[10.5px] text-subtle print:block">
        Generated by Proof from verified evidence. Each question cites the fact it is built on.
      </p>
    </>
  );
}
